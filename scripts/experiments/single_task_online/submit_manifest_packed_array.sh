#!/usr/bin/env bash
# Submit single-task manifest as packed Slurm array:
# one GPU per Slurm task, multiple rows can run concurrently on that GPU.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"

MANIFEST=""
GPU_TYPE="H100"
PACK_SIZE=4
RUNS_PER_GPU=2
MAX_CONCURRENT_JOBS=2
TIME_LIMIT="24:00:00"
MEMORY="128G"
CPUS=16
ACCOUNT=""
PYTHON_BIN="python"
DRY_RUN=0

usage() {
  cat <<'EOF'
Usage:
  submit_manifest_packed_array.sh --manifest <path> [options]

Required:
  --manifest PATH                 CSV manifest generated by build_manifest.py

Options:
  --gpu-type {H100|H200|L40S}     Target GPU type (default: H100)
  --pack-size N                   Rows per Slurm array task (default: 4)
  --runs-per-gpu N                Max concurrent rows on one GPU (default: 2)
  --max-concurrent-jobs N         Max concurrent Slurm array tasks (default: 2)
  --time HH:MM:SS                 Wall clock limit (default: 24:00:00)
  --mem SIZE                      Memory per task (default: 128G)
  --cpus N                        CPUs per task (default: 16)
  --account NAME                  Slurm account override
  --python-bin PATH               Python executable (default: python)
  --dry-run                       Print sbatch command without submitting

Notes:
  - Use packed mode only when each row has small enough GPU memory footprint.
  - Recommended first use: smoke and pilot quick-check on high-risk ICE tasks.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --manifest) MANIFEST="$2"; shift 2 ;;
    --gpu-type) GPU_TYPE="$(echo "$2" | tr '[:lower:]' '[:upper:]')"; shift 2 ;;
    --pack-size) PACK_SIZE="$2"; shift 2 ;;
    --runs-per-gpu) RUNS_PER_GPU="$2"; shift 2 ;;
    --max-concurrent-jobs) MAX_CONCURRENT_JOBS="$2"; shift 2 ;;
    --time) TIME_LIMIT="$2"; shift 2 ;;
    --mem) MEMORY="$2"; shift 2 ;;
    --cpus) CPUS="$2"; shift 2 ;;
    --account) ACCOUNT="$2"; shift 2 ;;
    --python-bin) PYTHON_BIN="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown argument: $1"; usage; exit 1 ;;
  esac
done

if [[ -z "${MANIFEST}" ]]; then
  echo "Error: --manifest is required."
  usage
  exit 1
fi

if [[ ! -f "${MANIFEST}" ]]; then
  echo "Error: manifest not found: ${MANIFEST}"
  exit 1
fi

if [[ "${PACK_SIZE}" -le 0 || "${RUNS_PER_GPU}" -le 0 || "${MAX_CONCURRENT_JOBS}" -le 0 ]]; then
  echo "Error: --pack-size, --runs-per-gpu, --max-concurrent-jobs must all be > 0"
  exit 1
fi

case "${GPU_TYPE}" in
  H100)
    PARTITION="gpu-h100"
    GRES="gpu:H100:1"
    DEFAULT_ACCOUNT="gts-agarg35"
    ;;
  H200)
    PARTITION="gpu-h200"
    GRES="gpu:h200:1"
    DEFAULT_ACCOUNT="gts-agarg35"
    ;;
  L40S)
    PARTITION="gpu-l40s"
    GRES="gpu:l40s:1"
    DEFAULT_ACCOUNT="gts-agarg35-ideas_l40s"
    ;;
  *)
    echo "Error: unsupported --gpu-type ${GPU_TYPE}. Use H100, H200, or L40S."
    exit 1
    ;;
esac

if [[ -z "${ACCOUNT}" ]]; then
  ACCOUNT="${DEFAULT_ACCOUNT}"
fi

NUM_ROWS="$(${PYTHON_BIN} - <<'PY' "${MANIFEST}"
import csv, sys
with open(sys.argv[1], newline='', encoding='utf-8') as f:
    n = sum(1 for _ in csv.DictReader(f))
print(n)
PY
)"

if [[ "${NUM_ROWS}" -le 0 ]]; then
  echo "Error: manifest has no rows: ${MANIFEST}"
  exit 1
fi

NUM_PACKS="$(${PYTHON_BIN} - <<'PY' "${NUM_ROWS}" "${PACK_SIZE}"
import math, sys
num_rows = int(sys.argv[1])
pack_size = int(sys.argv[2])
print(int(math.ceil(num_rows / pack_size)))
PY
)"

ARRAY_RANGE="0-$((NUM_PACKS - 1))%${MAX_CONCURRENT_JOBS}"
STAGE_NAME="$(${PYTHON_BIN} - <<'PY' "${MANIFEST}"
import csv, sys
with open(sys.argv[1], newline='', encoding='utf-8') as f:
    rows = list(csv.DictReader(f))
print(rows[0].get('stage', 'stage'))
PY
)"
JOB_NAME="sto_pack_${STAGE_NAME}_${GPU_TYPE}_${RUNS_PER_GPU}x"
LOG_DIR="${PROJECT_ROOT}/logs/slurm/single_task_online/${STAGE_NAME}"
mkdir -p "${LOG_DIR}"

SBATCH_CMD=(
  sbatch
  --job-name="${JOB_NAME}"
  --account="${ACCOUNT}"
  --partition="${PARTITION}"
  --qos=inferno
  --gres="${GRES}"
  --nodes=1
  --ntasks=1
  --cpus-per-task="${CPUS}"
  --mem="${MEMORY}"
  --time="${TIME_LIMIT}"
  --array="${ARRAY_RANGE}"
  --output="${LOG_DIR}/${JOB_NAME}_%A_%a.out"
  --error="${LOG_DIR}/${JOB_NAME}_%A_%a.err"
  --export="ALL,PROJECT_ROOT=${PROJECT_ROOT},MANIFEST=${MANIFEST},PYTHON_BIN=${PYTHON_BIN},PACK_SIZE=${PACK_SIZE},RUNS_PER_GPU=${RUNS_PER_GPU}"
  --wrap="cd ${PROJECT_ROOT} && source ~/.bashrc && conda activate pwm && export PYTHONPATH=${PROJECT_ROOT}/src:\$PYTHONPATH && export MUJOCO_GL=\${MUJOCO_GL:-egl} && export PYOPENGL_PLATFORM=\${PYOPENGL_PLATFORM:-egl} && export EGL_PLATFORM=\${EGL_PLATFORM:-surfaceless} && \$PYTHON_BIN scripts/experiments/single_task_online/run_manifest_pack.py --manifest \$MANIFEST --pack-index \$SLURM_ARRAY_TASK_ID --pack-size \$PACK_SIZE --max-parallel \$RUNS_PER_GPU --project-root ${PROJECT_ROOT} --python-bin \$PYTHON_BIN"
)

echo "Submitting packed manifest array:"
echo "  Manifest: ${MANIFEST}"
echo "  Rows: ${NUM_ROWS}"
echo "  Pack size: ${PACK_SIZE}"
echo "  Num packs: ${NUM_PACKS}"
echo "  Runs per GPU: ${RUNS_PER_GPU}"
echo "  GPU: ${GPU_TYPE} (${GRES})"
echo "  Partition: ${PARTITION}"
echo "  Account: ${ACCOUNT}"
echo "  Array: ${ARRAY_RANGE}"
echo "  Logs: ${LOG_DIR}"

if [[ "${DRY_RUN}" -eq 1 ]]; then
  printf 'Dry run sbatch command:\n'
  printf ' %q' "${SBATCH_CMD[@]}"
  printf '\n'
  exit 0
fi

"${SBATCH_CMD[@]}"
